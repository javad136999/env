import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const assetsDir = path.resolve("public/assets");
const entries = {};
for (const name of await readdir(assetsDir)) {
  if (!/\.(?:js|css)$/.test(name)) continue;
  const filePath = path.join(assetsDir, name);
  entries[`/assets/${name}`] = await readFile(filePath, "utf8");
}

const output = `// Generated by scripts/generate-vercel-assets.mjs.\nexport const assets = ${JSON.stringify(entries)} as const;\n`;
await writeFile("server/generatedAssets.ts", output);
console.log(`Generated ${Object.keys(entries).length} Vercel assets`);
